export const DICTIONARIES: Record<Lang, Dict> = {
  en: { ...en, ...storyEn, ...campaignEn, ...depthEn },
  pl: { ...pl, ...storyPl, ...campaignPl, ...depthPl },
};

let current: Lang = 'en';

export function setLang(lang: Lang): void {
  current = lang;
  document.documentElement.lang = lang;
}

export const getLang = (): Lang => current;

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = DICTIONARIES[current][key] ?? DICTIONARIES.en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}

/** Text from the campaign: a key, a literal, or a key with values, where a value may itself be a key. */
export function tx(text: Txt): string {
  if (typeof text === 'string') return t(text);
  const vars: Record<string, string | number> = {};
  for (const [k, v] of Object.entries(text.v)) vars[k] = typeof v === 'string' ? t(v) : v;
  return t(text.k, vars);
}
